export type ConverterUnit = 'inches' | 'swg' | 'awg';

export function convertToMM(value: string, unit: ConverterUnit): string | null {
  if (!value || value.trim() === '') return null;

  const cleanValue = value.trim();

  if (unit === 'inches') {
    const num = parseFloat(cleanValue);
    if (isNaN(num)) return null;
    return (num * 25.4).toFixed(1);
  }

  if (unit === 'awg') {
    const lookup = AWG_TO_MM[cleanValue];
    if (lookup) return lookup.toFixed(1);
    return null;
  }

  if (unit === 'swg') {
    const lookup = SWG_TO_MM[cleanValue];
    if (lookup) return lookup.toFixed(1);
    return null;
  }

  return null;
}
